int main() {
  const LegacyBlockStates legacy =
      LegacyBlockStates::load(FALCON_BLOCK_UPGRADE_LEGACY_DIR);
  const BlockStateUpgrader upgrader(
      BlockStateUpgrader::loadSchemas(FALCON_BLOCK_UPGRADE_SCHEMA_DIR));

  int failures = 0;
  int checks = 0;
  for (const ClientLegacyId &entry : CLIENT_IDS) {
    checks++;
    const std::string name =
        upgrader.upgrade(legacy.fromLegacy(entry.mId, 0)).getName();
    if (name != entry.mName) {
      failures++;
      std::printf("FAIL: legacy id %d gives %s, the client gives %s\n",
                  entry.mId, name.c_str(), entry.mName);
    }
  }

  // a meta the block never had falls back to meta 0, an unknown id to air
  checks += 3;
  if (upgrader.upgrade(legacy.fromLegacy(35, 14)).getName() !=
      "minecraft:red_wool") {
    failures++;
    std::printf("FAIL: red wool\n");
  }
  if (upgrader.upgrade(legacy.fromLegacy(1, 15)).getName() !=
      "minecraft:stone") {
    failures++;
    std::printf("FAIL: unknown meta of stone\n");
  }
  if (legacy.fromLegacy(4000, 0).getName() != "minecraft:air") {
    failures++;
    std::printf("FAIL: unknown id\n");
  }

  std::printf("%d checks, %d failures\n", checks, failures);
  return failures == 0 ? 0 : 1;
}
